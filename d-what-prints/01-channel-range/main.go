// Порядок событий: range читает 1 (рандеву с записью в небуферизированный
// канал), затем блокируется в ожидании следующего значения. Через ~500мс
// горутина закрывает канал — range завершается, печатается "done".
// Паники нет: close при живом читателе — штатная ситуация.
//
// Если убрать close(ch): main навсегда заблокируется в range, других
// работающих горутин не останется, и рантайм упадёт с
