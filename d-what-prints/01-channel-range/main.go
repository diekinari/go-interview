package main

import (
	"fmt"
	"time"
)

// Что выведет программа? Будет ли паника или deadlock?
// А если убрать close(ch) — что изменится?
//
// Сначала ответь письменно или вслух, потом скролль к разбору в конце файла.

func main() {
	ch := make(chan int)
	go func() {
		ch <- 1
		time.Sleep(500 * time.Millisecond)
		close(ch)
	}()

	for i := range ch {
		fmt.Println(i)
	}
	fmt.Println("done")
}

