package main

import (
	"fmt"
	"time"
)

// Что выведет / чем закончится программа? (реальный собес Lamoda)
// Дополнительно: можно ли поймать это через recover?
// Как исправить? Как обнаружить такие проблемы до прода?
//
// Сначала ответь, потом скролль к разбору.

var m = map[string]int{"a": 1}

func main() {
	go read()
	time.Sleep(1 * time.Microsecond)
	go write()
	time.Sleep(1 * time.Second)
}

func read() {
	for {
		fmt.Println(m["a"])
	}
}

func write() {
	for {
		m["a"] = 2
	}
}

