// ================================ РАЗБОР ================================
//
// Программа упадёт: "fatal error: concurrent map read and map write"
// (или concurrent map writes). Рантайм детектит одновременный доступ
// к мапе и роняет ПРОЦЕСС ЦЕЛИКОМ.
//
// Ключевое: это fatal error, а НЕ panic — recover его не поймает,
// никакой defer не спасёт.
//
// Исправления: sync.RWMutex вокруг доступа к мапе (RLock на чтение,
// Lock на запись) или sync.Map (для специфичных нагрузок).
//
// Обнаружение до прода: go run -race / go test -race — детектор гонок
// покажет и те гонки, которые в этот раз «повезло» не словить рантаймом.
// Помнить: -race ловит только гонки, случившиеся в конкретном прогоне.
