// ================================ РАЗБОР ================================
//
// (a) Go 1.22 и новее: числа 0..4 в произвольном порядке. С 1.22 переменная
//     цикла создаётся ЗАНОВО на каждой итерации, каждая горутина захватывает
//     свою копию.
//
// (b) До Go 1.22: почти наверняка "5 5 5 5 5" (порядок и значения не
//     гарантированы). Переменная i была ОДНА на весь цикл; замыкания
//     захватывали её по ссылке. К моменту запуска горутин цикл обычно
//     уже завершался, и все читали финальное значение 5.
//
// Классические исправления для старых версий (надо знать оба):
//   1) параметр:   go func(i int) { ... }(i)
//   2) затенение:  i := i  перед go func
//
// То же самое происходит и без горутин — например,
// при сборе слайса функций-замыканий в цикле. Механизм один: замыкание
// хранит ссылку на переменную, а не снимок значения.
