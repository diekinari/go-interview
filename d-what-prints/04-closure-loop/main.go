package main

import (
	"fmt"
	"sync"
)

// Что выведет программа: (a) на Go 1.22+; (b) на Go до 1.22?
// Классика всех собесов про замыкания и горутины.
//
// Сначала ответь, потом скролль к разбору.

func main() {
	var wg sync.WaitGroup
	for i := 0; i < 5; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			fmt.Println(i)
		}()
	}
	wg.Wait()
}

