package main

import (
	"fmt"
	"log"
	"net/http"
	"time"
)

// Задача: graceful shutdown HTTP-сервера.
//
// Ниже — рабочий сервис на :8080. Его хендлер отвечает через 2 секунды
// (это стенд, его не меняй). Сейчас по Ctrl+C или kill сервис умирает
// мгновенно и обрывает запросы, которые ещё обрабатываются.
//
// Доработай функцию main так, чтобы по SIGINT или SIGTERM:
//   - новые соединения больше не принимались;
//   - уже начатые запросы получали нормальный ответ;
//   - процесс завершался, как только начатые запросы обслужены,
//     но не позже чем через 5 секунд после сигнала;
//   - без активных запросов — завершался сразу;
//   - код выхода был 0.
//
// Проверка: go test ./...  (тест собирает программу, запускает её
// и шлёт ей сигналы; порт 8080 должен быть свободен).
// Руками: go run . и curl localhost:8080, Ctrl+C во время запроса.
//
// Вопрос для разбора: в каком порядке закрывать остальные ресурсы
// (БД, Kafka), если бы они были?

func slowHandler(w http.ResponseWriter, _ *http.Request) {
	time.Sleep(2 * time.Second)
	fmt.Fprintln(w, "ok")
}

func main() {
	mux := http.NewServeMux()
	mux.HandleFunc("/", slowHandler)

	log.Println("listening on :8080")
	if err := http.ListenAndServe(":8080", mux); err != nil {
		log.Fatal(err)
	}
}
